type RuntimeTemplateMatcher = {
  names: string[];
  pattern: RegExp;
  translated: string;
};

const runtimeTemplateMatchers = new Map<SupportedLanguage, RuntimeTemplateMatcher[]>();

function getRuntimeTemplateMatchers(language: Exclude<SupportedLanguage, "ko">): RuntimeTemplateMatcher[] {
  const cached = runtimeTemplateMatchers.get(language);
  if (cached) return cached;

  const matchers = Object.entries(STUDIO_RUNTIME_NATIVE[language]).flatMap(([source, translated]) => {
    const names = Array.from(source.matchAll(/\{(\w+)\}/g), (match) => match[1]);
    if (names.length === 0) return [];
    const segments = source.split(/\{\w+\}/g).map((segment) => segment.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
    const pattern = new RegExp(`^${segments.map((segment, index) => `${segment}${index < names.length ? "([\\s\\S]*?)" : ""}`).join("")}$`);
    return [{ names, pattern, translated }];
  });
  runtimeTemplateMatchers.set(language, matchers);
  return matchers;
}

export function getStudioRuntimeMessage(language: SupportedLanguage, value: string): string {
  if (language === "ko") return value;
  const catalog: Record<string, string> = STUDIO_RUNTIME_NATIVE[language];
  const direct = catalog[value];
  if (direct) return direct;

  for (const matcher of getRuntimeTemplateMatchers(language)) {
    const match = value.match(matcher.pattern);
    if (!match) continue;
    return matcher.names.reduce(
      (message, name, index) => message.replaceAll(`{${name}}`, match[index + 1] ?? ""),
      matcher.translated,
    );
  }
  return value;
}

export function formatStudioRuntimeMessage(
  language: SupportedLanguage,
  value: string,
  replacements: Record<string, string | number>,
): string {
  let message = getStudioRuntimeMessage(language, value);
  for (const [name, replacement] of Object.entries(replacements)) {
    message = message.replaceAll(`{${name}}`, String(replacement));
  }
  return message;
}
